package com.S1;

public class PrimitiveDataType {
    public static void main(String[] args) {
        byte a =10;
        int b=11;
        short c=1000;
        long d=1000000;
        float f=1000000.0f;
        System.out.println(a);
        System.out.println(b);
        System.out.println(c);
        System.out.println(d);
        System.out.println(f);
    }
}
